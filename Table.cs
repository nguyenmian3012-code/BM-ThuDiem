    public static bool TryNearest(double grams, out int listed, out double diem)
    {
        listed = 0;
        diem = 0;
        if (grams < Pts[0].G - 0.5 || grams > Pts[^1].G + 0.5) return false;
        var best = Pts[0];
        var bestDist = double.MaxValue;
        foreach (var pt in Pts)
        {
            var dist = Math.Abs(grams - pt.G);
            if (dist < bestDist - 1e-9 || (Math.Abs(dist - bestDist) < 1e-9 && pt.G < best.G))
            {
                best = pt;
                bestDist = dist;
            }
        }
        listed = best.G;
        diem = best.D;
        return true;
    }

    public static double EquivalentWet(double dry, double wet) => 5000.0 * wet / dry;
